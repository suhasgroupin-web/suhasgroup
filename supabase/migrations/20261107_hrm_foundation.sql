-- SUHAS GROUP HRM foundation
-- Run in Supabase SQL Editor after the existing SUHAS security migration.
begin;

create table if not exists public.hr_departments (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.hr_employees (
  id uuid primary key default gen_random_uuid(),
  user_id uuid unique references auth.users(id) on delete set null,
  employee_code text not null unique,
  full_name text not null,
  email text,
  phone text,
  department_id bigint references public.hr_departments(id) on delete set null,
  designation text,
  employment_type text not null default 'Full-time',
  joining_date date,
  employment_status text not null default 'active'
    check (employment_status in ('active','inactive','terminated')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.hr_attendance (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.hr_employees(id) on delete cascade,
  attendance_date date not null default current_date,
  check_in timestamptz,
  check_out timestamptz,
  status text not null default 'present'
    check (status in ('present','absent','late','half_day','leave')),
  notes text,
  created_at timestamptz not null default now(),
  unique(employee_id, attendance_date)
);

create table if not exists public.hr_leave_requests (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.hr_employees(id) on delete cascade,
  leave_type text not null,
  start_date date not null,
  end_date date not null,
  reason text,
  status text not null default 'pending'
    check (status in ('pending','approved','rejected','cancelled')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  check (end_date >= start_date)
);

create table if not exists public.hr_shifts (
  id bigint generated by default as identity primary key,
  name text not null unique,
  start_time time not null,
  end_time time not null,
  break_minutes integer not null default 0 check (break_minutes >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.hr_employee_shifts (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.hr_employees(id) on delete cascade,
  shift_id bigint not null references public.hr_shifts(id) on delete cascade,
  work_date date not null,
  created_at timestamptz not null default now(),
  unique(employee_id, work_date)
);

create table if not exists public.hr_payroll (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.hr_employees(id) on delete cascade,
  pay_period_start date not null,
  pay_period_end date not null,
  basic_salary numeric(12,2) not null default 0 check (basic_salary >= 0),
  allowances numeric(12,2) not null default 0 check (allowances >= 0),
  deductions numeric(12,2) not null default 0 check (deductions >= 0),
  net_salary numeric(12,2) generated always as (basic_salary + allowances - deductions) stored,
  payment_status text not null default 'draft'
    check (payment_status in ('draft','approved','paid')),
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  check (pay_period_end >= pay_period_start),
  unique(employee_id, pay_period_start, pay_period_end)
);

create index if not exists idx_hr_attendance_date on public.hr_attendance(attendance_date desc);
create index if not exists idx_hr_attendance_employee on public.hr_attendance(employee_id);
create index if not exists idx_hr_leave_status on public.hr_leave_requests(status, created_at desc);
create index if not exists idx_hr_payroll_period on public.hr_payroll(pay_period_start desc);

alter table public.hr_departments enable row level security;
alter table public.hr_employees enable row level security;
alter table public.hr_attendance enable row level security;
alter table public.hr_leave_requests enable row level security;
alter table public.hr_shifts enable row level security;
alter table public.hr_employee_shifts enable row level security;
alter table public.hr_payroll enable row level security;

-- HR data is private. Only OWNER/ADMIN can manage workforce-wide records.
drop policy if exists "HR admins manage departments" on public.hr_departments;
create policy "HR admins manage departments" on public.hr_departments
 for all to authenticated
 using (public.has_suhas_role(auth.uid(), array['OWNER','ADMIN']))
 with check (public.has_suhas_role(auth.uid(), array['OWNER','ADMIN']));

drop policy if exists "HR admins manage employees" on public.hr_employees;
create policy "HR admins manage employees" on public.hr_employees
 for all to authenticated
 using (public.has_suhas_role(auth.uid(), array['OWNER','ADMIN']))
 with check (public.has_suhas_role(auth.uid(), array['OWNER','ADMIN']));

drop policy if exists "HR admins manage attendance" on public.hr_attendance;
create policy "HR admins manage attendance" on public.hr_attendance
 for all to authenticated
 using (public.has_suhas_role(auth.uid(), array['OWNER','ADMIN']))
 with check (public.has_suhas_role(auth.uid(), array['OWNER','ADMIN']));

drop policy if exists "HR admins manage leave requests" on public.hr_leave_requests;
create policy "HR admins manage leave requests" on public.hr_leave_requests
 for all to authenticated
 using (public.has_suhas_role(auth.uid(), array['OWNER','ADMIN']))
 with check (public.has_suhas_role(auth.uid(), array['OWNER','ADMIN']));

drop policy if exists "HR admins manage shifts" on public.hr_shifts;
create policy "HR admins manage shifts" on public.hr_shifts
 for all to authenticated
 using (public.has_suhas_role(auth.uid(), array['OWNER','ADMIN']))
 with check (public.has_suhas_role(auth.uid(), array['OWNER','ADMIN']));

drop policy if exists "HR admins manage employee shifts" on public.hr_employee_shifts;
create policy "HR admins manage employee shifts" on public.hr_employee_shifts
 for all to authenticated
 using (public.has_suhas_role(auth.uid(), array['OWNER','ADMIN']))
 with check (public.has_suhas_role(auth.uid(), array['OWNER','ADMIN']));

drop policy if exists "HR admins manage payroll" on public.hr_payroll;
create policy "HR admins manage payroll" on public.hr_payroll
 for all to authenticated
 using (public.has_suhas_role(auth.uid(), array['OWNER','ADMIN']))
 with check (public.has_suhas_role(auth.uid(), array['OWNER','ADMIN']));

grant select, insert, update, delete on public.hr_departments, public.hr_employees,
 public.hr_attendance, public.hr_leave_requests, public.hr_shifts,
 public.hr_employee_shifts, public.hr_payroll to authenticated;
grant usage, select on all sequences in schema public to authenticated;

notify pgrst, 'reload schema';
commit;
