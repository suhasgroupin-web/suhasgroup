-- Repair: the admin job-posting form writes to public.jobs, but some project
-- deployments do not have the base jobs table. Create the expected table safely.
begin;

create table if not exists public.jobs (
  id bigint generated by default as identity primary key,
  title text not null,
  company text not null default 'SUHAS GROUP',
  category text,
  location text,
  job_type text,
  deadline date,
  description text,
  image_url text,
  source text not null default 'SUHAS GROUP',
  external_url text,
  job_code text,
  country text,
  salary text,
  experience text,
  requirements text,
  featured boolean not null default false,
  urgent boolean not null default false,
  status text not null default 'published'
    check (status in ('draft','published','closed')),
  published_at timestamptz,
  created_at timestamptz not null default now()
);

-- Keep older installations compatible when the table already exists.
alter table public.jobs add column if not exists title text;
alter table public.jobs add column if not exists company text default 'SUHAS GROUP';
alter table public.jobs add column if not exists category text;
alter table public.jobs add column if not exists location text;
alter table public.jobs add column if not exists job_type text;
alter table public.jobs add column if not exists deadline date;
alter table public.jobs add column if not exists description text;
alter table public.jobs add column if not exists image_url text;
alter table public.jobs add column if not exists source text default 'SUHAS GROUP';
alter table public.jobs add column if not exists external_url text;
alter table public.jobs add column if not exists job_code text;
alter table public.jobs add column if not exists country text;
alter table public.jobs add column if not exists salary text;
alter table public.jobs add column if not exists experience text;
alter table public.jobs add column if not exists requirements text;
alter table public.jobs add column if not exists featured boolean not null default false;
alter table public.jobs add column if not exists urgent boolean not null default false;
alter table public.jobs add column if not exists status text not null default 'published';
alter table public.jobs add column if not exists published_at timestamptz;
alter table public.jobs add column if not exists created_at timestamptz not null default now();

alter table public.jobs enable row level security;

drop policy if exists "jobs public read" on public.jobs;
create policy "jobs public read" on public.jobs
  for select to anon, authenticated
  using (status = 'published' or public.is_editor());

drop policy if exists "SUHAS owner/admin/editor manage jobs" on public.jobs;
create policy "SUHAS owner/admin/editor manage jobs" on public.jobs
  for all to authenticated
  using (public.is_editor())
  with check (public.is_editor());

grant select on public.jobs to anon, authenticated;
grant insert, update, delete on public.jobs to authenticated;
-- Identity columns do not require a separate sequence grant for inserts.

-- Notify PostgREST to refresh its schema cache after creating the table.
notify pgrst, 'reload schema';

commit;
