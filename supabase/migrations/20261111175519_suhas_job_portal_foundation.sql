begin;
create table if not exists public.jobs (
 id bigint generated by default as identity primary key,title text not null,company text not null default 'SUHAS GROUP',
 category text,location text,country text,job_type text,work_mode text,salary text,experience text,deadline date,
 description text,requirements text,image_url text,source text not null default 'SUHAS GROUP',external_url text,
 job_code text,featured boolean not null default false,urgent boolean not null default false,
 status text not null default 'published' check(status in ('draft','published','closed')),
 published_at timestamptz,created_at timestamptz not null default now()
);
alter table public.jobs add column if not exists work_mode text;
alter table public.jobs add column if not exists country text;
alter table public.jobs add column if not exists salary text;
alter table public.jobs add column if not exists experience text;
alter table public.jobs add column if not exists requirements text;
alter table public.jobs add column if not exists job_code text;
alter table public.jobs add column if not exists featured boolean not null default false;
alter table public.jobs add column if not exists urgent boolean not null default false;
alter table public.jobs add column if not exists status text not null default 'published';
alter table public.jobs add column if not exists published_at timestamptz;
create or replace function public.suhas_jobs_before_write() returns trigger language plpgsql set search_path=public as $$
begin
 if new.job_code is null or btrim(new.job_code)='' then
  new.job_code := 'SG-'||to_char(now() at time zone 'utc','YYMM')||'-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,6));
 end if;
 if new.status='published' and new.published_at is null then new.published_at:=now(); end if;
 return new;
end; $$;
drop trigger if exists suhas_jobs_before_write on public.jobs;
create trigger suhas_jobs_before_write before insert or update on public.jobs for each row execute function public.suhas_jobs_before_write();
create unique index if not exists jobs_job_code_key on public.jobs(job_code) where job_code is not null;
create unique index if not exists jobs_external_url_key on public.jobs(lower(external_url)) where external_url is not null and external_url<>'';
create index if not exists jobs_status_published_at_idx on public.jobs(status,published_at desc);
create index if not exists jobs_category_location_idx on public.jobs(category,location);
alter table public.jobs enable row level security;
drop policy if exists "SUHAS public read published jobs" on public.jobs;
create policy "SUHAS public read published jobs" on public.jobs for select to anon,authenticated using(status='published' or public.has_suhas_role(array['OWNER']));
drop policy if exists "SUHAS owner manage jobs" on public.jobs;
create policy "SUHAS owner manage jobs" on public.jobs for all to authenticated using(public.has_suhas_role(array['OWNER'])) with check(public.has_suhas_role(array['OWNER']));
grant select on public.jobs to anon,authenticated;
grant insert,update,delete on public.jobs to authenticated;

create table if not exists public.saved_jobs(user_id uuid not null references auth.users(id) on delete cascade,job_id bigint not null references public.jobs(id) on delete cascade,created_at timestamptz not null default now(),primary key(user_id,job_id));
alter table public.saved_jobs enable row level security;
drop policy if exists "SUHAS members manage own saved jobs" on public.saved_jobs;
create policy "SUHAS members manage own saved jobs" on public.saved_jobs for all to authenticated using((select auth.uid())=user_id) with check((select auth.uid())=user_id);
grant select,insert,delete on public.saved_jobs to authenticated;
create index if not exists saved_jobs_user_idx on public.saved_jobs(user_id);

create table if not exists public.applications(
 id bigint generated by default as identity primary key,
 job_id bigint not null references public.jobs(id) on delete cascade,
 user_id uuid not null references public.profiles(id) on delete cascade,
 cover_letter text,resume_url text,status text not null default 'new' check(status in ('new','reviewing','shortlisted','rejected','hired')),
 created_at timestamptz not null default now(),updated_at timestamptz not null default now(),
 constraint applications_user_job_unique unique(user_id,job_id)
);
alter table public.applications enable row level security;
drop policy if exists "SUHAS members read own applications" on public.applications;
create policy "SUHAS members read own applications" on public.applications for select to authenticated using((select auth.uid())=user_id or public.has_suhas_role(array['OWNER']));
drop policy if exists "SUHAS members apply to published jobs" on public.applications;
create policy "SUHAS members apply to published jobs" on public.applications for insert to authenticated with check((select auth.uid())=user_id and status='new' and exists(select 1 from public.jobs j where j.id=job_id and j.status='published'));
drop policy if exists "SUHAS owner update applications" on public.applications;
create policy "SUHAS owner update applications" on public.applications for update to authenticated using(public.has_suhas_role(array['OWNER'])) with check(public.has_suhas_role(array['OWNER']));
grant select,insert,update on public.applications to authenticated;
create index if not exists applications_job_created_idx on public.applications(job_id,created_at desc);
create index if not exists applications_user_created_idx on public.applications(user_id,created_at desc);
drop policy if exists "SUHAS owner read applicant profiles" on public.profiles;
create policy "SUHAS owner read applicant profiles" on public.profiles for select to authenticated using((select auth.uid())=id or public.has_suhas_role(array['OWNER']));

create table if not exists public.ai_usage_logs(id bigint generated by default as identity primary key,user_id uuid references auth.users(id) on delete set null,request_type text not null,model text,usage_data jsonb not null default '{}'::jsonb,status text not null default 'success',created_at timestamptz not null default now());
alter table public.ai_usage_logs enable row level security;
drop policy if exists "SUHAS members read own AI usage" on public.ai_usage_logs;
create policy "SUHAS members read own AI usage" on public.ai_usage_logs for select to authenticated using((select auth.uid())=user_id or public.has_suhas_role(array['OWNER']));
grant select on public.ai_usage_logs to authenticated;
create index if not exists ai_usage_logs_user_created_idx on public.ai_usage_logs(user_id,created_at desc);
insert into public.user_roles(user_id,role) select id,'OWNER' from auth.users where lower(email)='suhasgroup.in@gmail.com' and email_confirmed_at is not null on conflict(user_id) do update set role='OWNER';
notify pgrst,'reload schema';
commit;